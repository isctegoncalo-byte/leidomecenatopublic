import { Institution, NeedItem } from '../types'

type ProjectInput = Omit<NeedItem, 'id' | 'status' | 'implementationPhase'>

const photo = (id: string) => `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1200&q=80`

function projectText(input: ProjectInput) {
  const name = input.projectName || `${input.category}: ${input.subcategory}`
  const target = input.targetPopulation || 'pessoas abrangidas pela intervenção'
  const beneficiaries = input.beneficiaries
    ? `${input.beneficiaries.toLocaleString('pt-PT')} beneficiários diretos`
    : 'beneficiários diretos identificados pela instituição'
  const territory = input.generalImpactMetrics?.geographicScope || input.territorialScope?.districts?.join(', ') || 'território de intervenção indicado pela instituição'
  const duration = input.generalImpactMetrics?.durationMonths
    ? `${input.generalImpactMetrics.durationMonths} meses`
    : 'o período de execução previsto'
  const evidence = input.generalImpactMetrics?.evidenceMethod || 'registos de execução, indicadores de acompanhamento e evidências documentais'
  const reporting = input.generalImpactMetrics?.reportingFrequency || 'periódica'
  const metric = input.impactMetric || 'indicadores de execução e resultados'
  const support = input.supportType === 'produtos'
    ? `um apoio em produtos ou serviços, nomeadamente ${input.productOrService || input.subcategory}`
    : `um apoio financeiro de € ${(input.requestedAmount || input.totalProjectCost || 0).toLocaleString('pt-PT')}`
  const cost = (input.totalProjectCost || input.estimatedValue || input.requestedAmount || 0).toLocaleString('pt-PT')
  const secured = (input.securedFunding || 0).toLocaleString('pt-PT')
  const sdgs = input.sdgGoals.map(goal => `ODS ${goal}`).join(', ')
  const disclosure = input.disclosurePlan || 'comunicação regular dos resultados alcançados'
  const results = input.resultsPresentation || 'relatório final com execução, resultados e principais aprendizagens'

  const executiveSummary = `
${name} responde a uma necessidade concreta identificada pela instituição: ${input.description} O projeto dirige-se a ${target}, em ${territory}, e foi estruturado para produzir resultados verificáveis ao longo de ${duration}. A instituição pretende mobilizar ${support}, integrado num custo total estimado de € ${cost}, dos quais € ${secured} já se encontram assegurados ou identificados como financiamento complementar.

A métrica principal definida é: ${metric}. O projeto prevê impacto direto em ${beneficiaries} e está alinhado com ${sdgs}, permitindo acompanhar a execução com dados, evidências e comunicação de resultados. O plano de divulgação previsto assenta em ${disclosure}, com apresentação final através de ${results}.
  `.trim()

  const rationale = `
A fundamentação de ${name} assenta na existência de uma necessidade real, concreta e já observada pela instituição no seu trabalho diário. A descrição apresentada pela entidade identifica o problema central: ${input.description} Esta necessidade não surge de forma abstrata; está ligada a limitações de acesso, recursos insuficientes, fragilidades territoriais, barreiras económicas, ausência de equipamento adequado, pressão sobre equipas técnicas ou falta de condições para dar continuidade a uma resposta que já demonstrou utilidade. Por esse motivo, o projeto foi concebido como uma intervenção operacional e mensurável, em vez de uma intenção genérica.

O público-alvo definido é ${target}, com incidência em ${territory}. Este enquadramento territorial é relevante porque permite perceber onde a resposta será implementada, que comunidades serão abrangidas e que parceiros poderão ser mobilizados. Em muitos casos, a vulnerabilidade não está apenas na falta de recursos financeiros, mas também na distância, na dificuldade de transporte, na ausência de serviços especializados, na falta de equipamentos ou na escassez de oportunidades de participação. O projeto responde a esse contexto através de uma solução concreta, adequada à capacidade da instituição e proporcional ao valor solicitado.

A opção por ${support} decorre da avaliação feita pela instituição sobre o recurso mais crítico para desbloquear a intervenção. Quando o apoio é financeiro, o valor permite contratar serviços, executar obras, financiar bolsas, assegurar acompanhamento técnico ou pagar atividades essenciais. Quando o apoio é em produtos ou serviços, a prioridade está na obtenção de equipamento, tecnologia, materiais, viaturas, consumíveis ou outras soluções que reduzem custos e aceleram a resposta. Em ambos os casos, o donativo é canalizado para a instituição beneficiária e deve ser confirmado documentalmente pelas partes envolvidas.
  `.trim()

  const objectives = `
Os objetivos de ${name} orientam a execução e a validação do apoio. O primeiro objetivo é responder à necessidade descrita pela instituição, mobilizando ${support} para que a intervenção avance em ${territory}. O segundo é alcançar ${beneficiaries}, assegurando que o apoio chega ao público-alvo definido. O terceiro é recolher evidência através de ${evidence}, com reporte ${reporting}, para demonstrar recursos aplicados, atividades realizadas e resultados obtidos. O projeto deverá culminar em ${results}, garantindo informação clara para a instituição, para a empresa mecenas e para a futura comunicação de impacto.
  `.trim()

  return { executiveSummary, rationale, objectives }
}

function buildOdsImpactMetrics(input: ProjectInput): NonNullable<NeedItem['odsImpactMetrics']> {
  const direct = input.beneficiaries || 0
  const indirect = Number(input.generalImpactMetrics?.indirectBeneficiaries || 0)
  const totalPeople = Math.max(direct + indirect, direct, 1)
  const volunteers = Number(input.generalImpactMetrics?.volunteersInvolved || 0)
  const cost = Number(input.totalProjectCost || input.estimatedValue || input.requestedAmount || 0)
  const duration = Number(input.generalImpactMetrics?.durationMonths || 12)
  const hectares = Number(input.generalImpactMetrics?.geographicScope?.match(/(\d+)\s*hect/i)?.[1] || 0)

  const metricsFor = (sdg: number): Record<string, string | number> => {
    switch (sdg) {
      case 1:
        return {
          familiesSupported: Math.max(Math.round(totalPeople / 3), 1),
          basicNeedsCovered: input.category === 'Habitação' ? 'habitação, segurança e eficiência energética' : 'apoio social, educação e acompanhamento familiar',
        }
      case 2:
        return {
          mealsProvided: Math.max(direct * duration * 20, direct),
          foodWasteReducedKg: input.category === 'Alimentação' ? Math.max(Math.round(cost * 2.7), 1000) : 0,
        }
      case 3:
        return {
          healthSessions: Math.max(direct * 8, 12),
          patientsSupported: direct || totalPeople,
        }
      case 4:
        return {
          studentsSupported: direct || totalPeople,
          learningHours: Math.max((direct || totalPeople) * 40, 120),
        }
      case 5:
        return {
          womenGirlsSupported: Math.round((direct || totalPeople) * 0.55),
          genderActions: Math.max(Math.round(duration / 2), 1),
        }
      case 6:
        return {
          peopleWithWaterAccess: direct || totalPeople,
          waterSavedLiters: Math.max((direct || totalPeople) * 250, 1000),
        }
      case 7:
        return {
          energySavedKwh: Math.max(Math.round(cost * 0.8), 500),
          familiesEnergySupported: Math.max(Math.round((direct || totalPeople) / 3), 1),
        }
      case 8:
        return {
          jobsCreated: Math.max(Number(input.professionalsInvolved || 0), 1),
          peopleTrainedWork: direct || totalPeople,
        }
      case 9:
        return {
          equipmentUnits: input.productOrService ? Math.max(Math.round(cost / 12000), 1) : Math.max(Number(input.professionalsInvolved || 0), 1),
          innovationOutputs: 'kits, equipamentos, relatórios técnicos e materiais de capacitação',
        }
      case 10:
        return {
          vulnerablePeopleSupported: direct || totalPeople,
          accessBarriersRemoved: Math.max(Math.round((direct || totalPeople) / 25), 1),
        }
      case 11:
        return {
          communityUsers: totalPeople,
          spacesImproved: input.category === 'Habitação' ? Math.max(Math.round(direct / 4), 1) : Math.max(Math.round(Number(input.professionalsInvolved || 1) / 3), 1),
        }
      case 12:
        return {
          materialsReusedKg: input.category === 'Alimentação' ? Math.max(Math.round(cost * 1.8), 1000) : Math.max(Math.round(cost * 0.25), 250),
          wasteAvoidedKg: input.category === 'Alimentação' ? Math.max(Math.round(cost * 2.7), 1000) : Math.max(Math.round(cost * 0.3), 250),
        }
      case 13:
        return {
          co2AvoidedKg: Math.max(Math.round((hectares || direct || 10) * 1200), 1000),
          climateActions: Math.max(Math.round(duration / 2), 2),
        }
      case 14:
        return {
          marineAreaProtected: input.generalImpactMetrics?.geographicScope || 'zonas costeiras e estuarinas monitorizadas',
          plasticRemovedKg: Math.max(Math.round(cost * 0.03), 50),
        }
      case 15:
        return {
          treesPlanted: input.category === 'Ambiente' ? Math.max(Math.round(cost / 4), 1000) : 0,
          landRestoredHa: hectares || Math.max(Math.round(cost / 2500), 1),
        }
      case 16:
        return {
          justiceAccessActions: Math.max(Math.round(duration / 2), 2),
          peopleInclusionPrograms: direct || totalPeople,
        }
      case 17:
        return {
          partnersInvolved: Math.max(Math.round(volunteers / 10), 2),
          collaborationOutputs: 'protocolos, ações de parceria, relatórios e sessões de acompanhamento',
        }
      default:
        return {}
    }
  }

  return input.sdgGoals.reduce<NonNullable<NeedItem['odsImpactMetrics']>>((all, sdg) => ({
    ...all,
    [sdg]: metricsFor(sdg),
  }), {})
}

const project = (id: string, input: ProjectInput): NeedItem => ({
  ...input,
  ...projectText(input),
  odsImpactMetrics: buildOdsImpactMetrics(input),
  id,
  status: 'ativo',
  implementationPhase: 'candidatura',
})

const score = (
  environmental: number,
  social: number,
  governance: number,
  sdgAlignment: number[],
  beneficiaries: number,
  impactNarrative: string,
): Institution['esgScore'] => ({
  environmental,
  social,
  governance,
  total: Math.round(environmental * 0.35 + social * 0.45 + governance * 0.20),
  sdgAlignment,
  beneficiaries,
  impactNarrative,
  highlights: [],
  risks: [],
})

